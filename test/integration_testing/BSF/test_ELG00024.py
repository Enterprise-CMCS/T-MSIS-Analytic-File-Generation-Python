def test_create_builds_views_in_order(elg):
    """create() emits base -> recCt -> uniq -> multi_all -> multi_step2 -> multi -> final uniq views."""
    _, bsf = elg
    views = [re.search(r"temporary view\s+(\S+)", z, re.I).group(1) for _, z in bsf.sql]
    assert views == [
        f"{TAB}_base", f"{TAB}_recCt", f"{TAB}_uniq", f"{TAB}_multi_all",
        f"{TAB}_multi_step2", f"{TAB}_multi", f"{TAB}_{FILE_DATE}_uniq",
    ]
    assert all(name == "ELG00024" for name, _ in bsf.sql)



# ----------------------------------------------------------------------------- edge cases
def _run_segment(spark, bsf, rows, base):
    """Load source/base views, execute the generated SQL, return {msis: row-dict}."""
    spark.createDataFrame(rows, SRC_SCHEMA).createOrReplaceTempView(TAB)
    spark.createDataFrame(base, "submtg_state_cd string, msis_ident_num string") \
        .createOrReplaceTempView(f"ELG00021_{FILE_DATE}_uniq")
    for _, z in bsf.sql:
        spark.sql(z)
    out = spark.table(f"{TAB}_{FILE_DATE}_uniq").collect()
    return {r["msis_ident_num"]: r.asDict() for r in out}


def test_blank_msis_excluded_even_if_in_base(spark, elg):
    """A blank MSIS_IDENT_NUM is dropped even when the base population contains it."""
    _, bsf = elg
    rows = [_row("01", "  ", 1, D(2026, 1, 31), 1), _row("01", "G", 1, D(2026, 1, 31), 1)]
    result = _run_segment(spark, bsf, rows, [("01", "  "), ("01", "G")])
    assert set(result) == {"G"}


def test_null_effective_date_loses(spark, elg):
    """desc ordering puts a null CMNTY_ENGGMT_EFF_DT last, so a dated record wins despite lower REC_NUM."""
    _, bsf = elg
    rows = [
        _row("01", "H", 1, D(2026, 1, 31), 9, work="0", eff=None),
        _row("01", "H", 1, D(2026, 1, 31), 1, work="1"),
    ]
    result = _run_segment(spark, bsf, rows, [("01", "H")])
    assert result["H"]["WORK_FLAG"] == "1"


def test_sort_key_is_final_tie_breaker(spark, elg):
    """Identical dates and REC_NUM: the ascending sort_key decides, giving a deterministic winner."""
    _, bsf = elg
    step2 = re.sub(r"\s+", " ", bsf.sql[4][1])
    assert re.search(r"REC_NUM desc, coalesce\(trim\(adlt_grp_qualn\),'xx'\)", step2)
    rows = [
        _row("01", "J", 1, D(2026, 1, 31), 3, work="1"),
        _row("01", "J", 1, D(2026, 1, 31), 3, work="0"),
    ]
    result = _run_segment(spark, bsf, rows, [("01", "J")])
    assert result["J"]["WORK_FLAG"] == "0"


def test_multiids_where_suffix_and_no_tie_break(monkeypatch):
    """MultiIds honours suffix/val/where and omits the tie-breaker and created vars when not given."""
    monkeypatch.setattr(taf_elg.ELG, "create_initial_table", lambda self: None)
    bsf = FakeBSF()
    seg = ELG00024(bsf)
    seg.MultiIds("", where="t1.work_flag = '1'", suffix="_s", val="_base")
    multi_all, step2, multi = (z for _, z in bsf.sql)
    assert f"view {TAB}_s_multi_all" in multi_all
    assert f"from {TAB}_base as t1" in multi_all
    assert f"inner join {TAB}_s_recCt" in multi_all
    assert "where t1.work_flag = '1'" in multi_all
    assert re.search(r"select\s+t1\.\*\s+from", multi_all)
    assert re.search(r"REC_NUM desc\s*\)", step2)
    assert f"from {TAB}_s_multi_step2" in multi and "KEEP_FLAG = 1" in multi


